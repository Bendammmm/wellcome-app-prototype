export function getProductById(id: string): Product {
  return PRODUCTS.find((p) => p.id === id) || PRODUCTS[0];
}

export function getEffectiveItemMeta(productId: string, variantId?: string) {
  const product = getProductById(productId);
  const variant = variantId ? product.variants?.find((v) => v.id === variantId) : undefined;
  return {
    product,
    variant,
    title: variant ? variant.fullTitle : product.name,
    image: variant ? variant.image : product.image,
    price: variant ? variant.price : product.price,
    originalPrice: variant ? variant.originalPrice : product.originalPrice,
    unitPriceText: variant ? variant.unitPriceText : product.unitPriceText,
    isExtraLeadTime: variant ? !!variant.extraLeadTime : !!product.isExtraLeadTime,
  };
}
